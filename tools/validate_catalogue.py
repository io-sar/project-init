#!/usr/bin/env python3
"""Validate the practice catalogue: required fields, unique IDs, applies-tag grammar against profile dimensions,
tension references, and rebuild practices/INDEX.md. Usage: python3 tools/validate_catalogue.py (from the skill root)"""
import re, glob, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(ROOT)
DIMS = {"mode":["new","existing"],"stage":["prototype","mvp","production"],"team":["solo","small","multi-team"],
 "architecture":["monolith","modular-monolith","services"],"interfaces":["cli","web-ui","internal-api","public-api","events"],
 "data":["none","stored","personal","special-category"],"scale":["low","moderate","high"],
 "deployment":["local","paas","cloud","on-prem","regulated-env"],"ai":["none","uses-llm","agentic"],
 "regulation":["gdpr","nis2","ai-act","accessibility-eaa","cra","none"],"release":["continuous","scheduled","multi-version"],
 "horizon":["stays-small","grows","splits","high-scale"],"repo":["single","monorepo","polyrepo","submodules"],
 "shared":["no","yes"],"tracker":["jira","github","azure-boards","gitlab","other","none"],
 "openness":["closed","published","community"],"tenancy":["single","multi"],"platform":["no","yes"]}
FIELDS = ["applies","opt-in","kind","note","rule","why","alternatives","choose-when"]
problems, ids, rows = [], [], []
TOKEN = re.compile(r"\s*(\(|\)|AND\b|OR\b|NOT\b|always\b|([a-z\-]+)\s*(has-any|has|in|>=|<=|!=|=|>|<)\s*(\([^)]*\)|[a-z0-9\-]+))")
def check_tag(pid, a):
    pos = 0; a = a.strip()
    while pos < len(a):
        m = TOKEN.match(a, pos)
        if not m: problems.append(f"{pid}: cannot parse applies near '{a[pos:pos+30]}'"); return
        if m.group(2):
            d, op, v = m.group(2), m.group(3), m.group(4).strip("()")
            if d not in DIMS: problems.append(f"{pid}: unknown dimension '{d}'")
            else:
                for val in [x.strip() for x in v.split(",")]:
                    if val not in DIMS[d]: problems.append(f"{pid}: '{val}' is not a value of {d}")
                if op in ("has","has-any") and d not in ("interfaces","regulation"): problems.append(f"{pid}: '{op}' used on single-value dimension {d}")
        pos = m.end()
for f in sorted(glob.glob("practices/[0-9][0-9]-*.md")):
    t = open(f).read(); title = re.search(r"^# (.+)$", t, re.M).group(1)
    blocks = re.split(r"(?m)^(?=## \d\d\.\d+ )", t)[1:]; alts = 0
    for b in blocks:
        pid = b.split()[1]; ids.append(pid)
        found = re.findall(r"(?m)^- ([a-z\-]+): ", b)
        for k in ("applies","rule","why"):
            if k not in found: problems.append(f"{pid}: missing {k}")
        for k in found:
            if k not in FIELDS: problems.append(f"{pid}: unknown field {k}")
        if "alternatives" in found:
            alts += 1
            if "choose-when" not in found: problems.append(f"{pid}: alternatives without choose-when")
        m = re.search(r"(?m)^- applies: (.+)$", b)
        if m: check_tag(pid, m.group(1))
    rows.append((f, title, len(blocks), alts))
dups = sorted({i for i in ids if ids.count(i) > 1}); problems += [f"duplicate id {d}" for d in dups]
tens = open("guides/principle-tensions.md").read()
for ref in set(re.findall(r"\b(\d\d\.\d+)\b", tens)):
    if ref not in ids: problems.append(f"tensions guide references unknown practice {ref}")
for f in glob.glob("practices/[0-9][0-9]-*.md"):
    for t in re.findall(r"\bT(\d+)\b", open(f).read()):
        if not re.search(rf"\| T{t} \|", tens): problems.append(f"{f}: references missing tension T{t}")
version = re.search(r"Project init · (v[\d.]+)", open("SKILL.md").read()).group(1)
out = [f"# Practices index ({version}, language-agnostic)", "",
 "Source of truth: one file per group. Fields per practice: `applies` (see `../profile.md`), `rule`, `why`; optional `note`, `opt-in`, `kind`, `alternatives` + `choose-when` (see `../guides/principle-tensions.md`).", "",
 "| File | Group | Practices | With alternatives |", "|---|---|---|---|"]
out += [f"| `{os.path.basename(f)}` | {ti} | {n} | {a} |" for f, ti, n, a in rows]
out.append(f"| | **Total** | **{sum(r[2] for r in rows)}** | **{sum(r[3] for r in rows)}** |")
open("practices/INDEX.md", "w").write("\n".join(out) + "\n")
tags = [f"# Practice tags ({version})", "",
 "Generated by tools/validate_catalogue.py; do not edit by hand. One line per practice, for selection in Step 4: evaluate `applies` against the profile, then read only the selected practices in their group files.",
 "Flags: `alt` = has alternatives (resolve in Step 4.2), `opt-in` = only suggested, `setup` = applied as configuration.", "",
 "| ID | Title | applies | Flags |", "|---|---|---|---|"]
for f in sorted(glob.glob("practices/[0-9][0-9]-*.md")):
    for b in re.split(r"(?m)^(?=## \d\d\.\d+ )", open(f).read())[1:]:
        head = b.split("\n")[0][3:]; pid, title = head.split(" ", 1)
        a = re.search(r"(?m)^- applies: (.+)$", b).group(1)
        flags = [x for x, k in (("alt", "alternatives"), ("opt-in", "opt-in"), ("setup", "kind")) if re.search(rf"(?m)^- {k}: ", b)]
        tags.append(f"| {pid} | {title} | `{a}` | {' '.join(flags)} |")
open("practices/TAGS.md", "w").write("\n".join(tags) + "\n")
print(f"{sum(r[2] for r in rows)} practices in {len(rows)} groups, {sum(r[3] for r in rows)} with alternatives")
print("problems:" if problems else "problems: none"); [print("  -", p) for p in problems]
sys.exit(1 if problems else 0)
